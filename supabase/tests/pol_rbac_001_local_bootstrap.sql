CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE IF NOT EXISTS auth.users(id uuid PRIMARY KEY);
CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT (nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid
$$;
CREATE OR REPLACE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT COALESCE(nullif(current_setting('request.jwt.claims',true),'')::jsonb, '{}'::jsonb)
$$;
DO $$ BEGIN CREATE ROLE anon NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN CREATE ROLE authenticated NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
GRANT USAGE ON SCHEMA public,auth TO authenticated,anon;

CREATE TABLE public.studios(id uuid PRIMARY KEY);
CREATE TABLE public.studio_users(
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users(id),
  studio_id uuid NOT NULL REFERENCES public.studios(id),
  ruolo text NOT NULL,
  stato text NOT NULL,
  UNIQUE(user_id,studio_id)
);
CREATE TABLE public.patients(id bigint PRIMARY KEY,studio_id uuid NOT NULL REFERENCES public.studios(id));
CREATE TABLE public.appointments(id bigint PRIMARY KEY,studio_id uuid NOT NULL REFERENCES public.studios(id));

ALTER TABLE public.studio_users ENABLE ROW LEVEL SECURITY;
CREATE POLICY studio_users_own ON public.studio_users FOR SELECT TO authenticated USING (user_id=(SELECT auth.uid()));
GRANT SELECT ON public.studio_users TO authenticated;

