-- ── Patient balance for the assistant (service role only) ───────────────
CREATE OR REPLACE FUNCTION public.whatsapp_saldo_paziente_v1(p_studio_id uuid, p_paziente_id bigint)
RETURNS TABLE (piano_id bigint, titolo text, totale_piano numeric, totale_pagato numeric, saldo_piano numeric, scadenza_pagamento date)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF p_studio_id IS NULL OR p_paziente_id IS NULL THEN
    RETURN;
  END IF;
  -- Same tenant scoping the financial views use (see get_saldi_aperti_studio).
  PERFORM set_config('request.financial_studio_override_v1', p_studio_id::text, true);
  IF EXISTS (
    SELECT 1 FROM private.financial_live_data_quality_v1 q
    WHERE q.studio_id = p_studio_id AND q.blocking_metric = 'PLAN_BALANCE'
  ) THEN
    RAISE EXCEPTION 'POL-FIN-006: open balances unavailable due incomplete plan data';
  END IF;

  RETURN QUERY
  SELECT s.piano_id, plan.titolo, s.totale_piano, s.totale_pagato_piano,
         s.totale_piano - s.totale_pagato_piano, plan.scadenza_pagamento
  FROM private.incassi_plan_saldo_v1 s
  JOIN public.plans plan ON plan.id = s.piano_id
  WHERE s.studio_id = p_studio_id
    AND s.paziente_id = p_paziente_id
    AND plan.stato = 'accettato'
    AND s.totale_piano - s.totale_pagato_piano > 0.005
  ORDER BY plan.scadenza_pagamento NULLS LAST, s.piano_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.whatsapp_saldo_paziente_v1(uuid, bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.whatsapp_saldo_paziente_v1(uuid, bigint) TO service_role;

COMMENT ON FUNCTION public.whatsapp_saldo_paziente_v1(uuid, bigint) IS
  'POL-WA-003a: open balances of ONE patient for the WhatsApp assistant. Same source, acceptance gate and data-quality block as get_saldi_aperti_studio; callable only by service_role (the whatsapp-webhook Edge Function).';

COMMIT;
