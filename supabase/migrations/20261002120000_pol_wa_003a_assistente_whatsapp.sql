-- POL-WA-003a: the WhatsApp assistant becomes a real assistant.
-- Product Owner decisions (2026-10-02): appointments are PROPOSED by the
-- assistant and CONFIRMED by staff; the assistant always answers but pauses
-- on a conversation as soon as staff writes from the phone (Coexistence);
-- it gives studio info, the patient's own balance and recalls, and hands
-- over to staff when needed.
--
-- Additive only:
--   * richieste_prenotazione gains the columns a WhatsApp request needs, so
--     WhatsApp requests land in the SAME "Richieste di prenotazione" list the
--     Agenda already shows for the public booking page (no parallel flow).
--   * whatsapp_messages.origine tells patient / assistant / staff apart.
--   * whatsapp_conversazioni: per-number state (AI pause, staff hand-over).
--   * whatsapp_saldo_paziente_v1: service-role-only read of the patient's open
--     balances, the same query and acceptance gate as get_saldi_aperti_studio
--     (POL-FIN-006/007), restricted to one patient. No new financial formula.
--
-- Rollback (drops only what this file adds):
